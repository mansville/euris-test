CREATE SEQUENCE clienti_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE CLIENTI (
    ID INT DEFAULT clienti_seq.nextval PRIMARY KEY,
    VERSION INT DEFAULT 0 NOT NULL,
    NOME VARCHAR(255) NOT NULL,
    COGNOME VARCHAR(255) NOT NULL,
    DATA_NASCITA DATE NOT NULL,
    CODICE_FISCALE VARCHAR(16) UNIQUE NOT NULL,
    EMAIL VARCHAR(255) UNIQUE NOT NULL
);

CREATE SEQUENCE prodotti_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE PRODOTTI (
    ID INT DEFAULT prodotti_seq.nextval PRIMARY KEY,
    CODICE VARCHAR(255) UNIQUE NOT NULL,
    NOME VARCHAR(255) NOT NULL,
    STOCK INT CHECK (STOCK >= 0) NOT NULL,
    UPDATED_AT TIMESTAMP
);

CREATE SEQUENCE ordini_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE ORDINI (
    ID INT DEFAULT ordini_seq.nextval PRIMARY KEY,
    VERSION INT DEFAULT 0 NOT NULL,
    ID_CLIENTE INT NOT NULL,
    STATO VARCHAR(10) DEFAULT 'ORDINATO' NOT NULL,
    CREATED_AT TIMESTAMP,
    UPDATED_AT TIMESTAMP,
    CONSTRAINT fk_ordine_cliente FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTI(ID)
);

CREATE SEQUENCE dettaglio_ordini_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE DETTAGLIO_ORDINI (
    ID INT DEFAULT dettaglio_ordini_seq.nextval PRIMARY KEY,
    ID_ORDINE INT NOT NULL,
    ID_PRODOTTO INT NOT NULL,
    QUANTITA INT CHECK (QUANTITA > 0) NOT NULL,
    CONSTRAINT fk_dettaglio_ordine FOREIGN KEY (ID_ORDINE) REFERENCES ORDINI(ID) ON DELETE CASCADE,
    CONSTRAINT fk_dettaglio_prodotto FOREIGN KEY (ID_PRODOTTO) REFERENCES PRODOTTI(ID)
);